export const QUIZ = Object.fromEntries(ROWS.map(([id, question, answer, ...wrong]) => [id, { question, answer, wrong }]));

// Steady numbers from an id, so a card's choices come in the same order every time.
function seed(id) {
  let n = 0;
  for (const c of id) n = (Math.imul(n, 31) + c.charCodeAt(0)) >>> 0;
  return n;
}

// The question for a story place: { question, choices: [three, in a steady shuffled
// order], right: the index of the answer }, or null where there is none.
export function quizFor(id) {
  return arrange(id, QUIZ[id]);
}

// quiz: { question, answer, wrong: [two] } → the three choices in their steady order.
export function arrange(id, quiz) {
  if (!quiz) return null;
  const right = seed(id) % 3;
  const choices = [...quiz.wrong];
  choices.splice(right, 0, quiz.answer);
  return { question: quiz.question, choices, right };
}
